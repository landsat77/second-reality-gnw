#!/usr/bin/env python3
"""
The memory of the parts (src/port/sr_overlay.c).

The parts of the demo were separate programs: their variables (.bss) are
never used by another part. On the console the groups below share one
memory area (a linker OVERLAY): sr_overlay_load(group) clears it before the
part starts. Their initialised variables (.data, small) stay in the normal
.data, saved at start-up and restored at each load.

Order = enum Group of src/port/sr_glue.cpp.

  sr_overlays.py ld <dir>   writes <dir>/sr_overlays.ld (top level of
                            SECTIONS), <dir>/sr_overlays_data.ld (inside
                            .data) and <dir>/sr_overlays.h
"""
import os
import sys

GROUPS = [
    ('alku', ['ALKU_MAIN']),
    ('vector', ['U2A', 'U2E', 'VISU']),
    ('pam', ['OUTTAA']),
    ('beg', ['BeginTitleScreen']),
    ('glenz', ['GLENZ_MAIN']),
    ('tunneli', ['Tunneli']),
    ('koe', ['KOE']),
    ('shutdown', ['SHUTDOWN']),
    ('forest', ['Forest']),
    ('lens', ['LENS_MAIN']),
    ('plz', ['PLZ']),
    ('dots', ['DOTS_MAIN']),
    ('water', ['Water']),
    ('coman', ['COMAN_MAIN']),
    ('jplogo', ['JP']),
    ('end', ['END']),
    ('credits', ['CREDITS_MAIN']),
    ('endscrl', ['ENDSCRL_MAIN']),
]


def main():
    out = sys.argv[2]
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, 'sr_overlays.ld'), 'w') as f:
        f.write('/* generated by tools/sr_overlays.py: the variables of the parts, one group at a time */\n')
        f.write('. = ALIGN(32);\n__sr_ovl_start = .;\n')
        f.write('OVERLAY __sr_ovl_start : NOCROSSREFS\n{\n')
        for name, objs in GROUPS:
            f.write('  .sr_ovl_%s\n  {\n' % name)
            for o in objs:
                f.write('    *%s.o(.bss .bss.* COMMON)\n' % o)
            f.write('    . = ALIGN(32);\n  }\n')
        f.write('} >RAM_EMU :data\n')
        f.write('__sr_ovl_end = .;\n')
        for i, (name, _) in enumerate(GROUPS):
            f.write('__sr_ovl_size_%d = SIZEOF(.sr_ovl_%s);\n' % (i, name))
    with open(os.path.join(out, 'sr_overlays_data.ld'), 'w') as f:
        f.write('/* generated by tools/sr_overlays.py: the initialised variables of the parts */\n')
        f.write('. = ALIGN(4);\n__sr_parts_data_start = .;\n')
        for name, objs in GROUPS:
            for o in objs:
                f.write('*%s.o(.data .data.*)\n' % o)
        f.write('. = ALIGN(4);\n__sr_parts_data_end = .;\n')
    with open(os.path.join(out, 'sr_overlays.h'), 'w') as f:
        f.write('/* generated by tools/sr_overlays.py */\n#pragma once\n#include <stdint.h>\n')
        f.write('#define SR_GROUP_COUNT %d\n' % len(GROUPS))
        f.write('extern uint8_t __sr_ovl_start[], __sr_ovl_end[], __sr_parts_data_start[], __sr_parts_data_end[];\n')
        for i in range(len(GROUPS)):
            f.write('extern uint8_t __sr_ovl_size_%d[];\n' % i)
        f.write('static const char *const sr_group_names[SR_GROUP_COUNT] = { %s };\n'
                % ', '.join('"%s"' % n for n, _ in GROUPS))
        f.write('#define SR_GROUP_SIZES { %s }\n'
                % ', '.join('(uint32_t)__sr_ovl_size_%d' % i for i in range(len(GROUPS))))


if __name__ == '__main__':
    main()
