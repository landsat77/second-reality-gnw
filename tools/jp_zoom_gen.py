#!/usr/bin/env python3
"""
One-time conversion (kept for reference): the 54 unrolled zoom functions of
JP.cpp (Second Reality++, ~76 KB of ARM code) -> a table of operations
(src/sr_data/Parts/JPLOGO/JP_Zoom_Data.*, in the pack), run by
JPLogo::zoom_run() with the same effect.

  jp_zoom_gen.py <JP.cpp of Second Reality++> <out dir>
"""
import re
import sys

OPS = [
    (r'store_ax\(dst, (\d+)\);', 0),
    (r'mov_al_mem\(src, (\d+)\);', 1),
    (r'mov_ah_mem\(src, (\d+)\);', 2),
    (r'lens_demux_scanlineC\(g_ax\.AL\);', 3),
    (r'lens_demux_scanlineC\((\d+)\);', 4),
    (r'g_ax\.AL = (\d+); // mov al,\d+', 5),
    (r'store_al\(dst, (\d+)\);', 6),
    (r'dst\[(\d+)\] = g_ax\.AH;', 7),
    (r'xor_al_al\(\);', 8),
    (r'xor_ah_ah\(\);', 9),
]


def main():
    src = open(sys.argv[1]).read().split('\n')
    out = sys.argv[2]
    funcs = []
    i = 0
    while i < len(src):
        m = re.match(r'    void zoom(\d+)\(uint8_t \*( src)?, uint8_t \* dst\)$', src[i])
        if not m:
            i += 1
            continue
        name = int(m.group(1))
        assert src[i + 1] == '    {'
        i += 2
        ops = []
        while src[i] != '    }':
            line = src[i].strip()
            i += 1
            if not line:
                continue
            for pat, code in OPS:
                mm = re.fullmatch(pat, line)
                if mm:
                    v = int(mm.group(1)) if mm.groups() else 0
                    assert 0 <= v < 4096, (line, v)
                    ops.append(code << 12 | v)
                    break
            else:
                raise SystemExit('unknown: %r' % line)
        funcs.append((name, ops))
    allops = []
    starts = []
    for name, ops in funcs:
        starts.append((name, len(allops)))
        allops += ops
    total = len(allops)
    with open(out + '/JP_Zoom_Data.h', 'w') as f:
        f.write('#pragma once\n\n#include <stdint.h>\n\n'
                '// generated by tools/jp_zoom_gen.py from the zoom functions of JP.cpp\n'
                'namespace JPLogo::Data\n{\n'
                '    // op << 12 | operand; ops: see JPLogo::zoom_run()\n'
                '    extern const uint16_t zoom_ops[];\n'
                '    // zoomN: zoom_ops[zoom_start[i]] .. zoom_ops[zoom_start[i + 1]], N = zoom_name[i]\n'
                '    extern const uint16_t zoom_start[];\n'
                '    extern const uint16_t zoom_name[];\n'
                '}\n')
    with open(out + '/JP_Zoom_Data.cpp', 'w') as f:
        f.write('#include "JP_Zoom_Data.h"\n\nnamespace JPLogo::Data\n{\n')
        f.write('    const uint16_t zoom_ops[] = {\n')
        for k in range(0, total, 16):
            f.write('        ' + ', '.join('0x%04X' % v for v in allops[k:k + 16]) + ',\n')
        f.write('    };\n\n    const uint16_t zoom_start[] = {\n        ')
        f.write(', '.join(str(s) for _, s in starts) + ', %d,\n    };\n\n' % total)
        f.write('    const uint16_t zoom_name[] = {\n        ' + ', '.join(str(n) for n, _ in starts) + ',\n    };\n}\n')
    print('%d functions, %d ops' % (len(funcs), total))


if __name__ == '__main__':
    main()
